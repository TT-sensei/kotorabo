const ENTRIES = [...PAIRS].sort((a, b) => b[0].length - a[0].length);

export function applyFurigana(value) {
  if (!value) return "";
  const text = String(value);
  // 元の文字列を1回だけ走査し、各位置で最長一致した語にふりがなを付ける。
  // 置き換え後の文字列を再走査しないので、ruby が入れ子になることはない。
  let out = "";
  let i = 0;
  while (i < text.length) {
    let hit = null;
    for (const [word, reading] of ENTRIES) {
      if (text.startsWith(word, i)) { hit = [word, reading]; break; }
    }
    if (hit) {
      out += `<ruby>${hit[0]}<rt>${hit[1]}</rt></ruby>`;
      i += hit[0].length;
    } else {
      out += text[i];
      i += 1;
    }
  }
  return out;
}

